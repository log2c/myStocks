QString resolvedLanguageCode(const QString& language) {
    const QString normalized = i18n::normalizeLanguage(language);
    if (normalized != "auto") {
        return normalized;
    }

    const QString system = QLocale::system().name();
    if (system.startsWith("zh", Qt::CaseInsensitive)) {
        return "zh_CN";
    }
    return "en_US";
}

